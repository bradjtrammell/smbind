<?php
declare(strict_types=1);

namespace Smbind;

use PDO;
use RuntimeException;
use Throwable;

final class Publisher
{
    public function __construct(private PDO $db)
    {
    }

    private function command(array $command): void
    {
        $spec = [1 => ['pipe', 'w'], 2 => ['pipe', 'w']];
        $process = proc_open($command, $spec, $pipes);
        if (!is_resource($process)) {
            throw new RuntimeException('Unable to execute DNS validation or reload command.');
        }
        $stdout = stream_get_contents($pipes[1]);
        $stderr = stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);
        $exit = proc_close($process);
        if ($exit !== 0) {
            throw new RuntimeException(
                basename($command[0]) . ' failed (' . $exit . '): ' . substr(trim($stderr . "\n" . $stdout), 0, 1200)
            );
        }
    }

    private function atomic(string $path, string $content): void
    {
        $temp = tempnam(dirname($path), '.smbind-');
        if ($temp === false) {
            throw new RuntimeException('Cannot create a staging file in ' . dirname($path));
        }
        try {
            if (file_put_contents($temp, $content, LOCK_EX) !== strlen($content) ||
                !chmod($temp, 0640) || !rename($temp, $path)) {
                throw new RuntimeException('Could not atomically replace ' . $path);
            }
        } finally {
            if (is_file($temp)) {
                unlink($temp);
            }
        }
    }

    /**
     * Reject relative paths, symlink targets and paths that resolve inside the
     * HTTP document root. Realpath checks prevent ../ and symlink traversal.
     */
    private function outputPath(string $path, bool $directory = false): void
    {
        if (!str_starts_with($path, '/') || str_contains($path, "\0") || is_link($path)) {
            throw new RuntimeException('DNS publication paths must be absolute and must not be symlinks.');
        }
        $root = realpath(dirname(__DIR__) . '/public');
        $resolved = realpath($directory ? $path : dirname($path));
        if ($resolved === false || $root === false ||
            $resolved === $root || str_starts_with($resolved, $root . '/')) {
            throw new RuntimeException('DNS publication paths must resolve outside the HTTP document root.');
        }
    }

    private function original(string $path): ?string
    {
        if (is_link($path)) {
            throw new RuntimeException('Refusing to modify a symbolic link: ' . $path);
        }
        if (!file_exists($path)) {
            return null;
        }
        if (!is_file($path)) {
            throw new RuntimeException('Expected regular DNS file at ' . $path);
        }
        $bytes = file_get_contents($path);
        if ($bytes === false) {
            throw new RuntimeException('Cannot read DNS backup before publication: ' . $path);
        }
        return $bytes;
    }

    public function publish(): int
    {
        $directory = rtrim(setting('SMBIND_ZONE_DIR'), '/');
        $include = setting('SMBIND_INCLUDE_FILE');
        $conf = setting('SMBIND_NAMED_CONF');
        $checkZone = setting('SMBIND_NAMED_CHECKZONE', '/usr/sbin/named-checkzone');
        $checkConf = setting('SMBIND_NAMED_CHECKCONF', '/usr/sbin/named-checkconf');
        $rndc = setting('SMBIND_RNDC', '/usr/sbin/rndc');
        if (!is_dir($directory) || !is_writable($directory) ||
            !is_dir(dirname($include)) || !is_writable(dirname($include))) {
            throw new RuntimeException('Zone directory and include-file directory must be writable by the publisher.');
        }
        $this->outputPath($directory, true);
        $this->outputPath($include);
        if (is_link($directory . '/.publish.lock')) {
            throw new RuntimeException('Refusing to lock through a symbolic link.');
        }
        $lock = fopen($directory . '/.publish.lock', 'c');
        if ($lock === false || !flock($lock, LOCK_EX | LOCK_NB)) {
            throw new RuntimeException('Another DNS publication is already in progress.');
        }
        $backup = [];
        $written = [];
        try {
            $previousNames = $this->db->query('SELECT name FROM published_zones')->fetchAll(PDO::FETCH_COLUMN);
            $previousSet = array_fill_keys($previousNames, true);
            $zones = $this->db->query('SELECT * FROM zones ORDER BY name')->fetchAll(PDO::FETCH_ASSOC);
            $contents = [];
            $serials = [];
            $revisions = [];
            $includeLines = ['// Generated by SMBind. Do not edit this file.', ''];
            foreach ($zones as $zone) {
                $name = Dns::domain($zone['name']);
                $path = $directory . '/' . $name . '.zone';
                $this->outputPath($path);
                $zone['serial'] = (
                    (int) $zone['dirty'] === 1 ||
                    !isset($previousSet[$name]) ||
                    !is_file($path)
                ) ? Dns::nextSerial((int) $zone['serial']) : (int) $zone['serial'];
                $stmt = $this->db->prepare('SELECT host,type,value,ttl,priority,weight,port FROM records WHERE zone_id = ? ORDER BY host,type,id');
                $stmt->execute([$zone['id']]);
                $contents[$path] = Dns::render($zone, $stmt->fetchAll(PDO::FETCH_ASSOC));
                $serials[(int) $zone['id']] = $zone['serial'];
                $revisions[(int) $zone['id']] = (int) $zone['revision'];
                $includeLines[] = 'zone "' . $name . '" IN { type primary; file "' . $path . '"; };';
            }
            // Validate every new zone against a staging file before touching active output.
            $staging = [];
            try {
                foreach ($contents as $path => $content) {
                    $temp = tempnam($directory, '.check-');
                    if ($temp === false) {
                        throw new RuntimeException('Unable to stage a zone file.');
                    }
                    $staging[] = $temp;
                    if (file_put_contents($temp, $content) === false) {
                        throw new RuntimeException('Unable to stage a zone file.');
                    }
                    $this->command([$checkZone, basename($path, '.zone'), $temp]);
                }
            } finally {
                foreach ($staging as $file) {
                    if (is_file($file)) {
                        unlink($file);
                    }
                }
            }
            // Do not claim or overwrite files from other DNS tools.
            foreach ($zones as $zone) {
                $path = $directory . '/' . Dns::domain((string) $zone['name']) . '.zone';
                if (is_file($path) && !isset($previousSet[$zone['name']])) {
                    throw new RuntimeException('Refusing to replace a zone file not owned by SMBind: ' . $path);
                }
            }
            $existingInclude = $this->original($include) ?? '';
            if ($existingInclude === false ||
                ($existingInclude !== '' && !str_starts_with($existingInclude, '// Generated by SMBind.'))) {
                throw new RuntimeException('Refusing to replace an include file not generated by SMBind: ' . $include);
            }
            // Only remove files from the previous SMBind publication manifest; never touch independently managed zones.
            $desiredNames = array_column($zones, 'name');
            $retiredNames = array_values(array_diff($previousNames, $desiredNames));
            foreach ($retiredNames as $retired) {
                $retired = Dns::domain((string) $retired);
                $path = $directory . '/' . $retired . '.zone';
                $this->outputPath($path);
                $retiredContents = $this->original($path);
                if ($retiredContents !== null) {
                    $backup[$path] = $retiredContents;
                    if (!unlink($path)) {
                        throw new RuntimeException('Failed to remove a deleted managed DNS zone: ' . $retired);
                    }
                    $written[] = $path;
                }
            }
            $contents[$include] = implode("\n", $includeLines) . "\n";
            foreach ($contents as $path => $content) {
                $backup[$path] = $this->original($path);
                $this->atomic($path, $content);
                $written[] = $path;
            }
            $this->command([$checkConf, $conf]);
            $this->command([$rndc, 'reload']);

            $this->db->beginTransaction();
            try {
                $stmt = $this->db->prepare('UPDATE zones SET serial = GREATEST(serial, ?), dirty = CASE WHEN revision = ? THEN 0 ELSE 1 END WHERE id = ?');
                foreach ($serials as $id => $serial) {
                    $stmt->execute([$serial, $revisions[$id], $id]);
                }
                $this->db->exec('DELETE FROM published_zones');
                $manifest = $this->db->prepare('INSERT INTO published_zones (name) VALUES (?)');
                foreach ($desiredNames as $name) {
                    $manifest->execute([$name]);
                }
                $this->db->commit();
            } catch (Throwable $error) {
                $this->db->rollBack();
                throw $error;
            }
            return count($zones);
        } catch (Throwable $error) {
            // Restore the previously published data and attempt to reload it.
            foreach (array_reverse($written) as $path) {
                if ($backup[$path] === null) {
                    @unlink($path);
                } else {
                    try {
                        $this->atomic($path, $backup[$path]);
                    } catch (Throwable) {
                        // The original exception is still reported below.
                    }
                }
            }
            if ($written !== []) {
                try {
                    $this->command([$rndc, 'reload']);
                } catch (Throwable) {
                    // Manual intervention may be required; preserve original error.
                }
            }
            throw $error;
        } finally {
            flock($lock, LOCK_UN);
            fclose($lock);
        }
    }
}
