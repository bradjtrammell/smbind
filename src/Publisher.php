<?php
declare(strict_types=1);

namespace Smbind;

use PDO;
use RuntimeException;
use Throwable;

final class Publisher
{
    public function __construct(private PDO $db)
    {
    }

    private function command(array $command): void
    {
        $spec = [1 => ['pipe', 'w'], 2 => ['pipe', 'w']];
        $process = proc_open($command, $spec, $pipes);
        if (!is_resource($process)) {
            throw new RuntimeException('Unable to execute DNS validation or reload command.');
        }
        $stdout = stream_get_contents($pipes[1]);
        $stderr = stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);
        $exit = proc_close($process);
        if ($exit !== 0) {
            throw new RuntimeException(
                basename($command[0]) . ' failed (' . $exit . '): ' . substr(trim($stderr . "\n" . $stdout), 0, 1200)
            );
        }
    }

    private function atomic(string $path, string $content): void
    {
        $temp = tempnam(dirname($path), '.smbind-');
        if ($temp === false) {
            throw new RuntimeException('Cannot create a staging file in ' . dirname($path));
        }
        try {
            if (file_put_contents($temp, $content, LOCK_EX) !== strlen($content) ||
                !chmod($temp, 0640) || !rename($temp, $path)) {
                throw new RuntimeException('Could not atomically replace ' . $path);
            }
        } finally {
            if (is_file($temp)) {
                unlink($temp);
            }
        }
    }

    public function publish(): int
    {
        $directory = rtrim(setting('SMBIND_ZONE_DIR'), '/');
        $include = setting('SMBIND_INCLUDE_FILE');
        $conf = setting('SMBIND_NAMED_CONF');
        $checkZone = setting('SMBIND_NAMED_CHECKZONE', '/usr/sbin/named-checkzone');
        $checkConf = setting('SMBIND_NAMED_CHECKCONF', '/usr/sbin/named-checkconf');
        $rndc = setting('SMBIND_RNDC', '/usr/sbin/rndc');
        if (!is_dir($directory) || !is_writable($directory) ||
            !is_dir(dirname($include)) || !is_writable(dirname($include))) {
            throw new RuntimeException('Zone directory and include-file directory must be writable by the publisher.');
        }
        if (str_starts_with($directory . '/', dirname(__DIR__) . '/public/') ||
            str_starts_with($include, dirname(__DIR__) . '/public/')) {
            throw new RuntimeException('DNS zone output must not be under the public web root.');
        }
        $lock = fopen($directory . '/.publish.lock', 'c');
        if ($lock === false || !flock($lock, LOCK_EX | LOCK_NB)) {
            throw new RuntimeException('Another DNS publication is already in progress.');
        }
        $backup = [];
        $written = [];
        try {
            $zones = $this->db->query('SELECT * FROM zones ORDER BY name')->fetchAll(PDO::FETCH_ASSOC);
            $contents = [];
            $serials = [];
            $includeLines = ['// Generated by SMBind. Do not edit this file.', ''];
            foreach ($zones as $zone) {
                $name = Dns::domain($zone['name']);
                $path = $directory . '/' . $name . '.zone';
                $stmt = $this->db->prepare('SELECT host,type,value,ttl,priority,weight,port FROM records WHERE zone_id = ? ORDER BY host,type,id');
                $stmt->execute([$zone['id']]);
                $zone['serial'] = Dns::nextSerial((int) $zone['serial']);
                $contents[$path] = Dns::render($zone, $stmt->fetchAll(PDO::FETCH_ASSOC));
                $serials[(int) $zone['id']] = $zone['serial'];
                $includeLines[] = 'zone "' . $name . '" IN { type primary; file "' . $path . '"; };';
            }
            // Validate every new zone against a staging file before touching active output.
            $staging = [];
            try {
                foreach ($contents as $path => $content) {
                    $temp = tempnam($directory, '.check-');
                    if ($temp === false) {
                        throw new RuntimeException('Unable to stage a zone file.');
                    }
                    $staging[] = $temp;
                    if (file_put_contents($temp, $content) === false) {
                        throw new RuntimeException('Unable to stage a zone file.');
                    }
                    $this->command([$checkZone, basename($path, '.zone'), $temp]);
                }
            } finally {
                foreach ($staging as $file) {
                    if (is_file($file)) {
                        unlink($file);
                    }
                }
            }
            $contents[$include] = implode("\n", $includeLines) . "\n";
            foreach ($contents as $path => $content) {
                $backup[$path] = is_file($path) ? file_get_contents($path) : null;
                $this->atomic($path, $content);
                $written[] = $path;
            }
            $this->command([$checkConf, $conf]);
            $this->command([$rndc, 'reload']);

            $this->db->beginTransaction();
            try {
                $stmt = $this->db->prepare('UPDATE zones SET serial = ?, dirty = 0 WHERE id = ?');
                foreach ($serials as $id => $serial) {
                    $stmt->execute([$serial, $id]);
                }
                $this->db->commit();
            } catch (Throwable $error) {
                $this->db->rollBack();
                throw $error;
            }
            return count($zones);
        } catch (Throwable $error) {
            // Restore the previously published data and attempt to reload it.
            foreach (array_reverse($written) as $path) {
                if ($backup[$path] === null) {
                    @unlink($path);
                } else {
                    try {
                        $this->atomic($path, $backup[$path]);
                    } catch (Throwable) {
                        // The original exception is still reported below.
                    }
                }
            }
            if ($written !== []) {
                try {
                    $this->command([$rndc, 'reload']);
                } catch (Throwable) {
                    // Manual intervention may be required; preserve original error.
                }
            }
            throw $error;
        } finally {
            flock($lock, LOCK_UN);
            fclose($lock);
        }
    }
}
